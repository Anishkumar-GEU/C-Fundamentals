using System;
namespace LanguagePractice
{
	public class StaticClassAndMethods
	{
		// STATIC METHOD

		// static methods are the one that doesn't require any object to call.
		// concept of static methods comes into picture so that extra memory should not be assigned for object creation for non required objects.(basically where object creation is not required)

		// STATIC CLASS

		// static class are those that contain only static methods because we cannot create instance of a static class.
		// so static class comes into picture to ensure that the object is never been introduced for a static class to avoid unneccesary object allocation.
	}
}

