using System;
namespace LanguagePractice
{
	public class AccessModifiers
	{
        /*
		 
		 public – Accessible from anywhere.



		private – Accessible only within the same class or struct.



		protected – Accessible within the same class and its derived (child) classes.



		internal – Accessible anywhere within the same assembly (project).



		protected internal – Accessible within the same assembly OR from derived classes in another assembly.

		
        */
    }
}

